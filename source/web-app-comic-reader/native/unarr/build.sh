#!/bin/sh
# Compiles unarr's RAR reader and glue.c to WebAssembly.
#
# Runs INSIDE an Emscripten container; use scripts/build-unarr.sh to start it.
#   /src  this directory (native/unarr), read-only
#   /out  an empty scratch directory; the two outputs are copied from it
#         into public/vendor/unarr afterwards
set -eu

U=/src/upstream
GEN=/tmp/unarr-gen
mkdir -p "$GEN"

# The vendored sources must be the ones upstream.sha256 records. The build
# stamp covers that list and not the files themselves, so this is what ties
# the output to them.
(cd /src && sha256sum -c --quiet upstream.sha256)

# unarr.h is generated by CMake upstream; only the version is substituted.
VERSION=$(sed -n 's/^  VERSION \([0-9][0-9.]*\)$/\1/p' "$U/CMakeLists.txt")
[ -n "$VERSION" ] || { echo "could not read the unarr version from CMakeLists.txt" >&2; exit 1; }
MAJOR=${VERSION%%.*}
REST=${VERSION#*.}
MINOR=${REST%%.*}
PATCH=${REST#*.}
sed -e "s/@unarr_VERSION_MAJOR@/$MAJOR/" -e "s/@unarr_VERSION_MINOR@/$MINOR/" \
    -e "s/@unarr_VERSION_PATCH@/$PATCH/" -e "s/@unarr_VERSION@/$VERSION/" \
    "$U/unarr.h.in" > "$GEN/unarr.h"

# Only the RAR reader and what it needs: no zip, tar or 7z. Ppmd7aDec is the
# RAR flavour of the PPMd range decoder.
#
# -sDYNAMIC_EXECUTION=0 keeps eval() and new Function() out of the loader, so
# the module needs 'wasm-unsafe-eval' in the page's CSP and nothing more.
emcc -O2 -DNDEBUG -I"$GEN" -I"$U/common" \
  "$U"/common/conv.c "$U"/common/crc32.c "$U"/common/stream.c "$U"/common/unarr.c \
  "$U"/lzmasdk/CpuArch.c "$U"/lzmasdk/Ppmd7.c "$U"/lzmasdk/Ppmd7Dec.c "$U"/lzmasdk/Ppmd7aDec.c \
  "$U"/rar/filter-rar.c "$U"/rar/huffman-rar.c "$U"/rar/parse-rar.c "$U"/rar/rar.c \
  "$U"/rar/rarvm.c "$U"/rar/uncompress-rar.c \
  /src/glue.c \
  -sMODULARIZE=1 -sEXPORT_ES6=1 -sENVIRONMENT=web,worker,node \
  -sALLOW_MEMORY_GROWTH=1 -sSTACK_SIZE=1048576 \
  -sDYNAMIC_EXECUTION=0 \
  -sEXPORTED_FUNCTIONS=_malloc,_free \
  -sEXPORTED_RUNTIME_METHODS=HEAPU8,UTF8ToString \
  -o /out/unarr-rar.mjs

# Neither word appears anywhere in a clean loader, so match them bare: that
# also catches Function(...) without `new` and indirect eval.
if grep -q 'Function\|eval' /out/unarr-rar.mjs; then
  echo "the generated loader contains dynamic code evaluation" >&2
  exit 1
fi

echo "built unarr $VERSION with $(emcc --version | head -1)"
